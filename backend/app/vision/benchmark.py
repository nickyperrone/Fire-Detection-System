"""Field detection benchmark against the official cadastre (docs/10-field-detection.md#benchmark).

    python -m app.vision.benchmark [--per-province 30]

Writes docs/reports/field-detection.md. Images are cached in data/cache/sentinel2/, so a second
run only recomputes.
"""

import argparse
import json
import logging
import time
from dataclasses import dataclass
from datetime import UTC, datetime

import httpx
import numpy as np
from rasterio.features import rasterize
from rasterio.warp import transform_geom
from shapely.geometry import shape
from sqlalchemy import text

from app.config import REPO_ROOT, get_thresholds
from app.db import session_factory
from app.vision.field_detection import (
    CropHistory,
    DetectionError,
    cached_history,
    grow_field,
    outline,
)

CACHE_DIR = REPO_ROOT / "data" / "cache" / "sentinel2"
REPORT = REPO_ROOT / "docs" / "reports" / "field-detection.md"
SIMILARITIES = (0.06, 0.08, 0.1, 0.12)

# Rural parcels of 20-400 ha in one piece, in a fixed pseudo-random order so runs compare.
SAMPLE_SQL = text("""
    SELECT province, partida, ST_AsGeoJSON(geom) AS geometry, ST_Area(geom::geography) / 1e4 AS ha
    FROM (
        SELECT *, row_number() OVER (PARTITION BY province ORDER BY md5(partida::text)) AS n
        FROM cadastral_parcel
        WHERE ST_NumGeometries(geom) = 1
          AND ST_Area(geom::geography) BETWEEN 20e4 AND 400e4
          AND (status IS NULL OR status NOT ILIKE 'urban%')
    ) ranked
    WHERE n <= :per_province
    ORDER BY province, n
""")

log = logging.getLogger(__name__)


@dataclass
class Case:
    province: str
    partida: int
    hectares: float
    purity: float
    ious: dict[float, float | None]  # None: no field found


def purity(history: CropHistory, parcel: dict, similarity: float) -> float:
    """Share of the parcel whose crop history is close to the parcel's median one."""
    inside = rasterize(
        [transform_geom("EPSG:4326", history.crs, parcel)],
        out_shape=history.ndvi.shape[1:],
        transform=history.transform,
    ).astype(bool)
    pixels = history.ndvi[:, inside]
    median = np.median(pixels, axis=1)
    distance = np.sqrt(((pixels - median[:, None]) ** 2).mean(axis=0))
    return float((distance < similarity).mean())


def evaluate(row, history: CropHistory, config: dict) -> Case:
    parcel = json.loads(row.geometry)
    target = shape(parcel)
    tap = target.representative_point()
    seed = history.pixel(tap.y, tap.x)
    ious: dict[float, float | None] = {}
    for similarity in SIMILARITIES:
        try:
            field = grow_field(history.ndvi, seed, config | {"similarity": similarity})
        except DetectionError:
            ious[similarity] = None
            continue
        found = shape(outline(field, history, config))
        ious[similarity] = found.intersection(target).area / found.union(target).area
    return Case(
        row.province, row.partida, row.ha, purity(history, parcel, config["similarity"]), ious
    )


def summary(cases: list[Case], similarity: float) -> tuple[int, float, float, float]:
    scores = [c.ious[similarity] for c in cases]
    hits = [s or 0.0 for s in scores]
    return (
        len(cases),
        float(np.median(hits)) if hits else float("nan"),
        sum(s >= 0.7 for s in hits) / max(len(hits), 1),
        sum(s is None for s in scores) / max(len(scores), 1),
    )


def write_report(cases: list[Case], config: dict, seconds: float, today: str) -> None:
    single = [c for c in cases if c.purity >= config["benchmark_purity"]]
    lines = [
        "# Field detection benchmark",
        "",
        f"Generated by `make field-detection-benchmark` on {today}. Spec: "
        "[10-field-detection](../10-field-detection.md).",
        "",
        f"- Parcels sampled: {len(cases)} rural parcels of 20–400 ha from the cadastres in the "
        "database. "
        f"{len(single)} are one field (at least {config['benchmark_purity']:.0%} of the parcel "
        "has the same crop history); the rest hold several fields, and an outline cannot be "
        "scored against them.",
        "- Score: IoU between the outline found from a tap at the parcel's representative point "
        "and the parcel. 1 is a perfect match; 0.7 or more is an outline that only needs its "
        "corners checked.",
        '- "No field found" is an honest failure: the app asks to draw by hand.',
        f"- Time: {seconds / max(len(cases), 1):.1f} s per parcel, image reads included.",
        "",
        "## Single-field parcels",
        "",
        "| Similarity τ | Parcels | Median IoU | IoU ≥ 0.7 | No field found |",
        "|---|---|---|---|---|",
    ]
    for similarity in SIMILARITIES:
        n, median, good, missing = summary(single, similarity)
        chosen = " (in use)" if similarity == config["similarity"] else ""
        lines.append(f"| {similarity}{chosen} | {n} | {median:.2f} | {good:.0%} | {missing:.0%} |")
    lines += [
        "",
        f"## By province, τ = {config['similarity']}",
        "",
        "| Province | Single-field parcels | Median IoU | IoU ≥ 0.7 |",
        "|---|---|---|---|",
    ]
    for province in sorted({c.province for c in single}):
        n, median, good, _ = summary(
            [c for c in single if c.province == province], config["similarity"]
        )
        lines.append(f"| {province} | {n} | {median:.2f} | {good:.0%} |")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--per-province", type=int, default=30)
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    # Their per-request messages would bury the per-parcel results.
    for noisy in ("rasterio", "httpx"):
        logging.getLogger(noisy).setLevel(logging.WARNING)
    config = get_thresholds()["field_detection"]
    today = datetime.now(UTC).date()
    with session_factory()() as session:
        rows = session.execute(SAMPLE_SQL, {"per_province": args.per_province}).all()
    cases: list[Case] = []
    started = time.time()
    with httpx.Client() as client:
        for row in rows:
            tap = shape(json.loads(row.geometry)).representative_point()
            try:
                history = cached_history(client, tap.y, tap.x, config, today, CACHE_DIR)
            except DetectionError as exc:
                log.info("%s %s: %s", row.province, row.partida, exc.code)
                continue
            case = evaluate(row, history, config)
            cases.append(case)
            log.info("%s %s purity %.2f iou %s", row.province, row.partida, case.purity, case.ious)
    write_report(cases, config, time.time() - started, today.isoformat())
    print(f"wrote {REPORT}")


if __name__ == "__main__":
    main()
